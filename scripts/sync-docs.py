#!/usr/bin/env python3
"""Refresh QtProbe website pages and assets from repository documentation."""

import argparse
from pathlib import Path
import re
import shutil

ROOT = Path(__file__).resolve().parents[1]
SITE = ROOT / 'docs/site'
PUBLIC = SITE / 'public'
GUIDE = 'docs/qtprobe-guide.md'
# All level-two guide sections must be represented, in their source order.
SECTIONS = {
    'Getting started': '/get-started/first-run',
    'Build and launch': '/get-started/launch',
    'Command-line reference': '/reference/command-line',
    'Workspace and appearance': '/operate/workspace',
    'Dragging PVs from QtEDM and MEDM': '/operate/drag-and-drop',
    'Live values and controls': '/operate/values',
    'Adjusting values': '/operate/adjustments',
    'PV information': '/operate/information',
    'Structure browser': '/operate/structures',
    'Record explorer': '/operate/records',
    'Array inspection': '/operate/arrays',
    'History and statistics': '/operate/history',
    'Export and sessions': '/operate/files',
    'Help and manuals': '/operate/help',
    'Keyboard shortcuts': '/reference/keyboard-shortcuts',
    'Troubleshooting': '/operate/troubleshooting',
    'Compatibility and current limits': '/understand/compatibility',
}
ROUTES = {
    GUIDE: '/get-started/first-run',
    'README.md': '/get-started/install',
    'qtprobe/tests/README.md': '/develop/testing',
    'docs/performance.md': '/understand/performance',
    'LICENSE': '/project/license',
    'docs/site/develop/documentation.md': '/develop/documentation',
}
# Keep these exact paths in docs/site/.gitignore. Cleanup never globs authored pages.
GENERATED_PAGES = tuple(route.lstrip('/') + '.md' for route in SECTIONS.values()) + (
    'get-started/install.md', 'develop/testing.md',
    'understand/performance.md', 'project/license.md',
)


def read(name):
    return (ROOT / name).read_text(encoding='utf-8')


def anchor(title):
    return re.sub(r'\s+', '-', re.sub(r'[^\w\s-]', '', title.lower()))


def guide_sections():
    parts = re.split(r'^## (.+)\n', read(GUIDE), flags=re.MULTILINE)
    sections = list(zip(parts[1::2], parts[2::2]))
    if [title for title, _ in sections] != list(SECTIONS):
        raise ValueError('Guide headings changed; update SECTIONS, navigation and docs/site/.gitignore')
    return sections


def rewrite(text, origin):
    """Map source-document links, including guide fragments, to website routes."""
    def link(match):
        image, label, target = match.groups()
        if re.match(r'^[a-zA-Z][a-zA-Z0-9+.-]*:', target) or target.startswith('/'):
            return match.group(0)
        name, _, fragment = target.partition('#')
        source = ((ROOT / origin).parent / name).resolve() if name else ROOT / origin
        key = source.relative_to(ROOT).as_posix()
        if image and key.startswith('docs/screenshots/') and source.is_file():
            return f'![{label}](/images/{source.name})'
        route = ROUTES.get(key)
        if key == GUIDE and fragment:
            destinations = {anchor(title): route for title, route in SECTIONS.items()}
            if fragment not in destinations:
                raise ValueError(f'{origin}: unregistered guide fragment {fragment}')
            route = destinations[fragment]
        elif key == 'README.md' and fragment in ('', 'build-and-run'):
            fragment = ''
        if route is None:
            if not name:
                return match.group(0)
            raise ValueError(f'{origin}: unregistered documentation link {target}')
        return f'[{label}]({route}' + ('#' + fragment if fragment else '') + ')'
    return re.sub(r'(!?)\[([^\]]*)\]\(([^)]+)\)', link, text)


def write(route, title, content, origin, fragment=None):
    relative = route.lstrip('/') + '.md'
    if relative not in GENERATED_PAGES:
        raise ValueError(f'Register generated page for cleanup: {relative}')
    path = SITE / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    heading = '# ' + title + (f' {{#{fragment}}}' if fragment else '')
    path.write_text(f'<!-- Generated by scripts/sync-docs.py from {origin}; edit that source. -->\n\n'
                    + heading + '\n\n' + rewrite(content.strip(), origin) + '\n', encoding='utf-8')


def clean(dependencies=False):
    paths = [SITE / name for name in GENERATED_PAGES]
    paths += [PUBLIC / 'images', PUBLIC / 'downloads', SITE / '.vitepress/cache',
              SITE / 'dist', ROOT / 'docs/html']
    if dependencies:
        paths.append(SITE / 'node_modules')
    for path in paths:
        if path.is_symlink() or path.is_file():
            path.unlink()
        elif path.is_dir():
            shutil.rmtree(path)
    print('Removed generated documentation' + (' and dependencies.' if dependencies else '.'))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    modes = parser.add_mutually_exclusive_group()
    modes.add_argument('--clean', action='store_true')
    modes.add_argument('--distclean', action='store_true')
    args = parser.parse_args()
    if args.clean or args.distclean:
        clean(dependencies=args.distclean)
        return
    sections = guide_sections()
    ignored = read('docs/site/.gitignore').splitlines()
    if any('/' + name not in ignored for name in GENERATED_PAGES):
        raise ValueError('Register every generated page in docs/site/.gitignore')
    for title, body in sections:
        write(SECTIONS[title], title, body, GUIDE, fragment=anchor(title))
    readme = read('README.md').split('## Build and run\n', 1)[1]
    readme = re.split(r'^## ', readme, maxsplit=1, flags=re.MULTILINE)[0]
    write('/get-started/install', 'Install & build QtProbe', readme, 'README.md')
    for source in ('qtprobe/tests/README.md', 'docs/performance.md'):
        title, body = read(source).split('\n', 1)
        if source == 'docs/performance.md':
            body = ('::: info Dated engineering measurements\n'
                    'These results describe the recorded workloads and platforms, '
                    'not current performance guarantees.\n:::\n\n' + body)
        write(ROUTES[source], title.lstrip('# '), body, source)
    write('/project/license', 'License', 'The original Probe license is reproduced below. '
          'Source-file copyright notices are retained.\n\n```text\n'
          + read('LICENSE').rstrip() + '\n```', 'LICENSE')
    # Recreate copied assets so removed sources do not remain in later builds.
    for directory in (PUBLIC / 'images', PUBLIC / 'downloads'):
        if directory.exists():
            shutil.rmtree(directory)
    shutil.copytree(ROOT / 'docs/screenshots', PUBLIC / 'images')
    (PUBLIC / 'downloads').mkdir(parents=True, exist_ok=True)
    shutil.copy2(ROOT / GUIDE, PUBLIC / 'downloads/qtprobe-guide.md')
    print(f'Refreshed {len(GENERATED_PAGES)} pages, screenshots and the guide download.')


if __name__ == '__main__':
    main()
